    private const string BasicRpc = """
        using NetPulse;
        using NetPulse.Common;

        namespace Game
        {
            public partial class Hero : NetworkBehaviour
            {
                [NetRpc(RpcTarget.Others, Delivery = DeliveryMode.UnreliableSequenced, OwnerOnly = true)]
                private void Hit(int damage, string source)
                {
                }

                [NetRpc]
                public void Heal(float amount, NetRpcInfo info)
                {
                }

                public void Test()
                {
                    Rpc.Hit(1, "a");
                    Rpc.To(RpcTarget.All).Heal(2f);
                    Rpc.To(new Player(3)).Heal(2f);
                }
            }
        }
        """;

    [Fact]
    public void GeneratedCodeStartsWithAutoGeneratedMarkerAndHasNoComments()
    {
        var result = Harness.Run(BasicRpc);

        foreach (var text in result.Generated.Values)
        {
            Assert.StartsWith("// <auto-generated/>", text);
            Assert.DoesNotContain("///", text);
            Assert.Equal(1, text.Split('\n').Count(l => l.TrimStart().StartsWith("//")));
        }

        Assert.NotEmpty(result.Generated);
    }

    [Fact]
    public void BasicRpcCompilesWithoutDiagnosticsAndUsesTheContractNames()
    {
        var result = Harness.Run(BasicRpc);
        var text = result.AllGenerated;

        Assert.Empty(result.CompileProblems);
        Assert.Empty(result.GeneratorDiagnostics);
        Assert.Contains("protected RpcCalls Rpc => new RpcCalls(this, null, null);", text);
        Assert.DoesNotContain("protected new RpcCalls", text);
        Assert.Contains("public readonly struct RpcCalls", text);
        Assert.Contains("public RpcCalls To(global::NetPulse.RpcTarget target)", text);
        Assert.Contains("public RpcCalls To(global::NetPulse.Player player)", text);
        Assert.Contains("_owner.BeginRpc()", text);
        Assert.Contains("_owner.SendRpc(", text);
        Assert.Contains("protected override bool InvokeGeneratedRpc(ushort rpcId, global::NetPulse.Common.NetReader reader, in global::NetPulse.NetRpcInfo info)", text);
        Assert.Contains("return base.InvokeGeneratedRpc(rpcId, reader, in info);", text);
        Assert.Contains("global::NetPulse.RpcTarget.Others", text);
        Assert.Contains("global::NetPulse.Common.DeliveryMode.UnreliableSequenced", text);
        Assert.Contains("global::NetPulse.RpcTarget.All", text);
        Assert.Contains("Heal(__a0, info);", text);
    }

