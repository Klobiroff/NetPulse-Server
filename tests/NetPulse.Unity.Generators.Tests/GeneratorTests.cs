    [Fact]
    public void SyncVarsRegisterInDeclarationOrderWithBaseChaining()
    {
        const string source = """
            using System.Collections.Generic;
            using NetPulse;
            using UnityEngine;

            namespace Game
            {
                public enum Team
                {
                    Red,
                    Blue
                }

                public partial class Unit : NetworkBehaviour
                {
                    private readonly SyncVar<int> _health = new SyncVar<int>(100);
                    private readonly SyncVar<string> _title = new SyncVar<string>("", SyncPermission.Master);
                    private readonly SyncVar<Team> _team = new SyncVar<Team>();
                    private readonly SyncVar<List<Vector3>> _path = new SyncVar<List<Vector3>>();
                    private static int _ignored = 1;
                    private int _plain = 2;

                    public int Total => _health.Value + _plain + _ignored;
                }

                public partial class Hero : Unit
                {
                    private readonly SyncVar<float> _mana = new SyncVar<float>();
                }
            }
            """;

        var result = Harness.Run(source);
        Assert.Empty(result.CompileProblems);

        var unit = result.Generated["Game.Unit.NetPulse.g.cs"];
        Assert.Contains("protected override void RegisterSyncVars(global::NetPulse.SyncVarCollector collector)", unit);
        Assert.Contains("base.RegisterSyncVars(collector);", unit);
        Assert.Contains("collector.Add(_health, static (w, v) => w.WriteInt(v), static r => r.ReadInt());", unit);
        Assert.Contains("collector.Add(_title, static (w, v) => w.WriteString(v), static r => r.ReadString());", unit);
        Assert.True(unit.IndexOf("_health", StringComparison.Ordinal) < unit.IndexOf("_title", StringComparison.Ordinal));
        Assert.True(unit.IndexOf("_title", StringComparison.Ordinal) < unit.IndexOf("_team", StringComparison.Ordinal));
        Assert.DoesNotContain("_ignored", unit);
        Assert.DoesNotContain("_plain", unit);
        Assert.DoesNotContain("InvokeGeneratedRpc", unit);
        Assert.Contains("base.RegisterSyncVars(collector);", result.Generated["Game.Hero.NetPulse.g.cs"]);

        var assembly = result.Load();
        var hero = Activator.CreateInstance(assembly.GetType("Game.Hero")!)!;
        var collector = assembly.GetType("NetPulse.NetworkBehaviour")!.GetMethod("CollectForTest")!.Invoke(hero, null)!;
        var registered = (List<string>)collector.GetType().GetProperty("Registered")!.GetValue(collector)!;
        Assert.Equal(new[] { "Int32", "String", "Team", "List`1", "Single" }, registered);
    }

    [Fact]
    public void NetMessageRegistersExtendedTypeAndMessageWithTheFullNameId()
    {
        const string source = """
            using NetPulse;

            namespace Game
            {
                public partial struct Chat : INetMessage
                {
                    public string Text;
                    public int Channel;
                }

                public partial class Join : INetMessage
                {
                    public Player Who;
                    public Join Next;
                }
            }
            """;

        var result = Harness.Run(source);
        Assert.Empty(result.CompileProblems);

        var chat = result.Generated["Game.Chat.NetPulse.g.cs"];
        var chatId = StableId.Compute("Game.Chat");
        Assert.Contains("NetTypeRegistry.RegisterExtended<Chat>(" + chatId + ",", chat);
        Assert.Contains("NetMessageRegistry.Register<Chat>(" + chatId + ",", chat);
        Assert.Contains("[global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]", chat);
        Assert.Contains("#if UNITY_EDITOR", chat);
        Assert.Contains("[global::UnityEditor.InitializeOnLoadMethod]", chat);
        Assert.Contains("public static void NetWrite(global::NetPulse.Common.NetWriter writer, in Chat value)", chat);
        Assert.Contains("public static Chat NetRead(global::NetPulse.Common.NetReader reader)", chat);

        var assembly = result.Load();
        assembly.GetType("Game.Chat")!.GetNestedType("__NetPulseRegistration", System.Reflection.BindingFlags.NonPublic)!
            .GetMethod("Register", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!.Invoke(null, null);
        Assert.True(NetTypeRegistry.IsExtendedRegistered(chatId));

        var registry = assembly.GetType("NetPulse.NetMessageRegistry")!.GetProperty("Registered")!.GetValue(null)!;
        Assert.True(((System.Collections.IDictionary)registry).Contains(chatId));
        NetTypeRegistry.UnregisterExtended(chatId);
    }

    [Fact]
    public void SerializableTypesRoundTripThroughObjectContext()
    {
        const string source = """
            using NetPulse;

            namespace Game
            {
                [NetSerializable]
                public partial class Stats
                {
                    public int Hp;
                    public string Name { get; set; }
                    public int Hidden { get; private set; }
                    public readonly int Skipped;
                    public int Computed => 1;
                }

                public static class Boot
                {
                    public static void Run() => Stats.__NetPulseRegistration.Register();
                }
            }
            """;

        var result = Harness.Run(source.Replace("Stats.__NetPulseRegistration.Register();", "typeof(Stats).GetNestedType(\"__NetPulseRegistration\", System.Reflection.BindingFlags.NonPublic).GetMethod(\"Register\", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static).Invoke(null, null);"));
        Assert.Empty(result.CompileProblems);

        var assembly = result.Load();
        var type = assembly.GetType("Game.Stats")!;
        var id = StableId.Compute("Game.Stats");
        assembly.GetType("Game.Boot")!.GetMethod("Run")!.Invoke(null, null);

        try
        {
            var value = Activator.CreateInstance(type)!;
            type.GetField("Hp")!.SetValue(value, 12);
            type.GetProperty("Name")!.SetValue(value, "zed");

            var writer = new NetWriter();
            writer.WriteObject(value);
            var bytes = writer.ToArray();
            Assert.Equal(NetTypeCode.Extended, bytes[0]);
            Assert.Equal(id, (ushort)(bytes[1] | (bytes[2] << 8)));

            var back = new NetReader(bytes).ReadObject()!;
            Assert.Equal(12, type.GetField("Hp")!.GetValue(back));
            Assert.Equal("zed", type.GetProperty("Name")!.GetValue(back));
            Assert.Equal(0, type.GetProperty("Hidden")!.GetValue(back));

            var nullWriter = new NetWriter();
            type.GetMethod("NetWrite")!.Invoke(null, new object?[] { nullWriter, null });
            Assert.Equal(new byte[] { 0 }, nullWriter.ToArray());
            Assert.Null(type.GetMethod("NetRead")!.Invoke(null, new object?[] { new NetReader(new byte[] { 0 }) }));
        }
        finally
        {
            NetTypeRegistry.UnregisterExtended(id);
        }
    }

    [Fact]
    public void ReadOfCollectionsRejectsCountsLargerThanTheRemainingData()
    {
        const string source = """
            using NetPulse;

            namespace Game
            {
                [NetSerializable]
                public partial struct Bag
                {
                    public int[] Items;
                }
            }
            """;

        var result = Harness.Run(source);
        Assert.Empty(result.CompileProblems);

        var type = result.Load().GetType("Game.Bag")!;
        var writer = new NetWriter();
        writer.WriteVarUInt(1_000_000);
        var read = type.GetMethod("NetRead")!;

        var failure = Assert.Throws<System.Reflection.TargetInvocationException>(() => read.Invoke(null, new object?[] { new NetReader(writer.ToArray()) }));
        Assert.IsType<NetSerializationException>(failure.InnerException);
    }

