    [Fact]
    public void InheritanceChainsBaseCallsAndUsesNewOnlyWhenBaseHasGeneratedRpc()
    {
        const string source = """
            using NetPulse;

            namespace Game
            {
                public partial class Animal : NetworkBehaviour
                {
                    [NetRpc]
                    public void Eat(int amount)
                    {
                    }

                    [NetRpc]
                    private void Hidden()
                    {
                    }
                }

                public partial class Dog : Animal
                {
                    [NetRpc]
                    public void Bark(bool loud)
                    {
                    }

                    public void Test()
                    {
                        Rpc.Bark(true);
                        Rpc.Eat(2);
                    }
                }

                public partial class Puppy : Dog
                {
                    public void Test2()
                    {
                        Rpc.Bark(false);
                    }
                }

                public partial class Plain : NetworkBehaviour
                {
                }

                public partial class Cat : Plain
                {
                    [NetRpc]
                    public void Meow()
                    {
                    }
                }
            }
            """;

        var result = Harness.Run(source);

        Assert.Empty(result.CompileProblems);
        Assert.Contains("protected new RpcCalls Rpc", result.Generated["Game.Dog.NetPulse.g.cs"]);
        Assert.Contains("public new readonly struct RpcCalls", result.Generated["Game.Dog.NetPulse.g.cs"]);
        Assert.Contains("public void Eat(int amount)", result.Generated["Game.Dog.NetPulse.g.cs"]);
        Assert.DoesNotContain("Hidden", result.Generated["Game.Dog.NetPulse.g.cs"]);
        Assert.Contains("base.InvokeGeneratedRpc", result.Generated["Game.Dog.NetPulse.g.cs"]);
        Assert.DoesNotContain("protected new", result.Generated["Game.Animal.NetPulse.g.cs"]);
        Assert.DoesNotContain("protected new", result.Generated["Game.Cat.NetPulse.g.cs"]);
        Assert.False(result.Generated.ContainsKey("Game.Puppy.NetPulse.g.cs"));
        Assert.False(result.Generated.ContainsKey("Game.Plain.NetPulse.g.cs"));
    }

    [Fact]
    public void AllSupportedParameterTypesCompileAndRoundTripThroughTheGeneratedCode()
    {
        const string source = """
            using System;
            using System.Collections.Generic;
            using NetPulse;
            using UnityEngine;

            namespace Game
            {
                public enum Mode : byte
                {
                    A,
                    B
                }

                public enum Wide : long
                {
                    X = 1L << 40
                }

                [NetSerializable]
                public partial struct Point
                {
                    public int X;
                    public int Y { get; set; }
                }

                [NetSerializable]
                public partial class Box
                {
                    public Point Corner;
                    public string Label;
                    public List<Point> Points { get; set; }
                    public Point[] More;
                }

                public partial class Kitchen : NetworkBehaviour
                {
                    public static string Last;

                    [NetRpc]
                    public void Everything(
                        bool a, byte b, sbyte c, short d, ushort e, int f, uint g, long h, ulong i, float j, double k, char l, string m, Guid n,
                        Mode o, Wide p, Vector2 q, Vector3 r, Vector4 s, Quaternion t, Color u, Color32 v, Vector2Int w, Vector3Int x, Rect y,
                        Player z, NetworkObject aa, int[] ab, List<string> ac, Point ad, Box ae, Point[] af, List<List<int>> ag, string[][] ah, NetRpcInfo info)
                    {
                        Last = a + "|" + b + "|" + c + "|" + d + "|" + e + "|" + f + "|" + g + "|" + h + "|" + i + "|" + j + "|" + k + "|" + l + "|" + m + "|" + n + "|" + o + "|" + p
                            + "|" + z.ActorId + "|" + aa.ViewId + "|" + string.Join(",", ab) + "|" + string.Join(",", ac) + "|" + ad.X + "," + ad.Y
                            + "|" + ae.Label + ae.Corner.X + ae.Points.Count + ae.More.Length + "|" + af.Length + "|" + ag[1][0] + "|" + ah[1][1] + "|" + info.SenderActorId;
                    }

                    public void Send() => Rpc.Everything(
                        true, 2, -3, -4, 5, -6, 7, -8, 9, 1f, 2d, 'x', "str", new Guid("11111111-1111-1111-1111-111111111111"),
                        Mode.B, Wide.X, default, default, default, default, default, default, default, default, default,
                        new Player(4), new NetworkObject { ViewId = 77 }, new[] { 1, 2 }, new List<string> { "p", "q" }, new Point { X = 8, Y = 9 },
                        new Box { Corner = new Point { X = 5 }, Label = "L", Points = new List<Point> { new Point(), new Point() }, More = new Point[3] },
                        new Point[2], new List<List<int>> { new List<int>(), new List<int> { 42 } }, new[] { new string[0], new[] { "a", "b" } });
                }
            }
            """;

        var result = Harness.Run(source);
        Assert.Empty(result.CompileProblems);

        var assembly = result.Load();
        var type = assembly.GetType("Game.Kitchen")!;
        var instance = Activator.CreateInstance(type)!;
        type.GetMethod("Send")!.Invoke(instance, null);

        var behaviour = assembly.GetType("NetPulse.NetworkBehaviour")!;
        var sent = (System.Collections.IList)behaviour.GetProperty("Sent")!.GetValue(null)!;
        var entry = sent[sent.Count - 1]!;
        var id = (ushort)entry.GetType().GetProperty("Key")!.GetValue(entry)!;
        var data = (byte[])entry.GetType().GetProperty("Value")!.GetValue(entry)!;

        Assert.Equal(StableId.Compute("Everything"), id);
        var invoked = (bool)behaviour.GetMethod("InvokeForTest")!.Invoke(instance, new object?[] { id, data, Activator.CreateInstance(assembly.GetType("NetPulse.Player")!, 9) })!;
        Assert.True(invoked);

        var last = (string)type.GetField("Last")!.GetValue(null)!;
        Assert.Equal("True|2|-3|-4|5|-6|7|-8|9|1|2|x|str|11111111-1111-1111-1111-111111111111|B|X|4|77|1,2|p,q|8,9|L523|2|42|b|9", last);
    }

