using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace NetPulse.Unity.Generators
{
    [Generator]
    public sealed class NetPulseGenerator : ISourceGenerator
    {
        private const string Writer = "global::NetPulse.Common.NetWriter";
        private const string Reader = "global::NetPulse.Common.NetReader";
        private const string Never = "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]";

        public void Initialize(GeneratorInitializationContext context) => context.RegisterForSyntaxNotifications(() => new Receiver());

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxReceiver is Receiver receiver))
            {
                return;
            }

            var known = KnownSymbols.Create(context.Compilation);

            if (!known.IsUsable)
            {
                return;
            }

            var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
            var usedNames = new HashSet<string>();

            foreach (var declaration in receiver.Candidates)
            {
                var model = context.Compilation.GetSemanticModel(declaration.SyntaxTree);

                if (!(model.GetDeclaredSymbol(declaration) is INamedTypeSymbol symbol) || !seen.Add(symbol))
                {
                    continue;
                }

                var source = Emit(symbol, known);

                if (source == null)
                {
                    continue;
                }

                var hint = HintName(symbol);

                while (!usedNames.Add(hint))
                {
                    hint += "_";
                }

                context.AddSource(hint + ".NetPulse.g.cs", SourceText.From(source, Encoding.UTF8));
            }
        }

        internal static string Emit(INamedTypeSymbol symbol, KnownSymbols known)
        {
            var isBehaviour = known.IsNetworkBehaviour(symbol);
            var isSerializable = known.IsSerializableType(symbol) && !symbol.IsGenericType && !symbol.IsAbstract;
            var rpcs = isBehaviour ? Discovery.BuildRpcSet(symbol, known) : null;
            var syncVars = isBehaviour ? Discovery.SyncVars(symbol, known) : new List<SyncVarModel>();
            var hasRpc = rpcs != null && rpcs.Own.Count > 0;

            if (!hasRpc && syncVars.Count == 0 && !isSerializable)
            {
                return null;
            }

            var code = new CodeWriter();
            code.Line("// <auto-generated/>");
            code.Line("#nullable disable");
            var closers = OpenContainers(code, symbol);

            if (hasRpc)
            {
                EmitRpcs(code, symbol, rpcs);
            }

            if (syncVars.Count > 0)
            {
                if (hasRpc)
                {
                    code.Line();
                }

                EmitSyncVars(code, syncVars);
            }

            if (isSerializable)
            {
                if (hasRpc || syncVars.Count > 0)
                {
                    code.Line();
                }

                EmitSerializable(code, symbol, known);
            }

            for (var i = 0; i < closers; i++)
            {
                code.Close();
            }

            return code.ToString();
        }

        private static int OpenContainers(CodeWriter code, INamedTypeSymbol symbol)
        {
            var chain = new List<INamedTypeSymbol>();

            for (var current = symbol; current != null; current = current.ContainingType)
            {
                chain.Insert(0, current);
            }

            var opened = 0;
            var ns = symbol.ContainingNamespace;

            if (ns != null && !ns.IsGlobalNamespace)
            {
                code.Open("namespace " + ns.ToDisplayString());
                opened++;
            }

            foreach (var type in chain)
            {
                var keyword = type.TypeKind == TypeKind.Struct ? "struct" : "class";
                code.Open("partial " + keyword + " " + DisplayName(type));
                opened++;
            }

            return opened;
        }

        private static string DisplayName(INamedTypeSymbol type)
        {
            if (type.TypeParameters.Length == 0)
            {
                return Discovery.Escape(type.Name);
            }

            return Discovery.Escape(type.Name) + "<" + string.Join(", ", type.TypeParameters.Select(p => p.Name)) + ">";
        }

        private static string HintName(INamedTypeSymbol symbol)
        {
            var builder = new StringBuilder();

            foreach (var ch in Discovery.FullName(symbol))
            {
                builder.Append(char.IsLetterOrDigit(ch) || ch == '.' ? ch : '_');
            }

            if (symbol.TypeParameters.Length > 0)
            {
                builder.Append('_').Append(symbol.TypeParameters.Length);
            }

            return builder.ToString();
        }

        private static void EmitRpcs(CodeWriter code, INamedTypeSymbol symbol, RpcSet rpcs)
        {
            var typeName = DisplayName(symbol);
            var hide = rpcs.BaseHasRpc ? "new " : "";
            var access = symbol.IsSealed ? "private " : "protected ";
            code.Line(access + hide + "RpcCalls Rpc => new RpcCalls(this, null, null);");
            code.Line();
            code.Open("public " + hide + "readonly struct RpcCalls");
            code.Line("private readonly " + typeName + " _owner;");
            code.Line("private readonly global::NetPulse.RpcTarget? _target;");
            code.Line("private readonly global::NetPulse.Player _player;");
            code.Line();
            code.Open("public RpcCalls(" + typeName + " owner, global::NetPulse.RpcTarget? target, global::NetPulse.Player player)");
            code.Line("_owner = owner;");
            code.Line("_target = target;");
            code.Line("_player = player;");
            code.Close();
            code.Line();
            code.Line("public RpcCalls To(global::NetPulse.RpcTarget target) => new RpcCalls(_owner, target, null);");
            code.Line();
            code.Line("public RpcCalls To(global::NetPulse.Player player) => new RpcCalls(_owner, null, player);");

            foreach (var rpc in rpcs.Own.Concat(rpcs.Inherited))
            {
                code.Line();
                EmitRpcCall(code, rpc);
            }

            code.Close();
            code.Line();
            code.Line(Never);
            code.Open("protected override bool InvokeGeneratedRpc(ushort rpcId, " + Reader + " reader, in global::NetPulse.NetRpcInfo info)");
            code.Open("switch (rpcId)");

            foreach (var rpc in rpcs.Own)
            {
                code.Line("case " + rpc.Id + ":");
                code.Open("");
                var arguments = new List<string>();

                for (var i = 0; i < rpc.Params.Count; i++)
                {
                    var local = "__a" + i;
                    code.Line("var " + local + " = " + rpc.Params[i].Ser.EmitRead(code, "reader") + ";");
                    arguments.Add(local);
                }

                if (rpc.AcceptsInfo)
                {
                    arguments.Add("info");
                }

                code.Line(Discovery.Escape(rpc.Name) + "(" + string.Join(", ", arguments) + ");");
                code.Line("return true;");
                code.Close();
            }

            code.Line("default:");
            code.Line("    return base.InvokeGeneratedRpc(rpcId, reader, in info);");
            code.Close();
            code.Close();
        }

        private static void EmitRpcCall(CodeWriter code, RpcModel rpc)
        {
            var parameters = string.Join(", ", rpc.Params.Select(p => p.Ser.TypeName + " " + Discovery.Escape(p.Name)));
            code.Open("public void " + Discovery.Escape(rpc.Name) + "(" + parameters + ")");
            code.Line("var __w = _owner.BeginRpc();");

            foreach (var parameter in rpc.Params)
            {
                parameter.Ser.EmitWrite(code, "__w", Discovery.Escape(parameter.Name));
            }

            code.Line("_owner.SendRpc(" + rpc.Id + ", _target ?? " + rpc.TargetExpression + ", _player, __w, " + rpc.DeliveryExpression + ", " + (rpc.OwnerOnly ? "true" : "false") + ");");
            code.Close();
        }

        private static void EmitSyncVars(CodeWriter code, List<SyncVarModel> syncVars)
        {
            code.Line(Never);
            code.Open("protected override void RegisterSyncVars(global::NetPulse.SyncVarCollector collector)");
            code.Line("base.RegisterSyncVars(collector);");

            foreach (var syncVar in syncVars)
            {
                EmitCollectorAdd(code, Discovery.Escape(syncVar.Field.Name), syncVar.Ser);
            }

            code.Close();
        }

        private static void EmitCollectorAdd(CodeWriter code, string field, TypeSer ser)
        {
            var write = ser.WriteExpression("w", "v");
            var read = ser.ReadExpression("r");

            if (write != null && read != null)
            {
                code.Line("collector.Add(" + field + ", static (w, v) => " + write + ", static r => " + read + ");");
                return;
            }

            code.Line("collector.Add(");
            code.Line("    " + field + ",");
            code.Open("    static (w, v) =>");
            ser.EmitWrite(code, "w", "v");
            code.Close(",");
            code.Open("    static r =>");
            var result = ser.EmitRead(code, "r");
            code.Line("return " + result + ";");
            code.Close(");");
        }

        private static void EmitSerializable(CodeWriter code, INamedTypeSymbol symbol, KnownSymbols known)
        {
            var name = DisplayName(symbol);
            var members = Discovery.SerializableMembers(symbol, known).Where(m => m.Ser != null).ToList();
            var isClass = symbol.TypeKind == TypeKind.Class;

            code.Line(Never);
            code.Open("public static void NetWrite(" + Writer + " writer, in " + name + " value)");

            if (isClass)
            {
                code.Open("if (value == null)");
                code.Line("writer.WriteBool(false);");
                code.Line("return;");
                code.Close();
                code.Line("writer.WriteBool(true);");
            }

            foreach (var member in members)
            {
                member.Ser.EmitWrite(code, "writer", "value." + Discovery.Escape(member.Name));
            }

            code.Close();
            code.Line();
            code.Line(Never);
            code.Open("public static " + name + " NetRead(" + Reader + " reader)");

            if (isClass)
            {
                code.Line("if (!reader.ReadBool())");
                code.Line("{");
                code.Line("    return null;");
                code.Line("}");
                code.Line();
                code.Line("var result = new " + name + "();");
            }
            else
            {
                code.Line("var result = default(" + name + ");");
            }

            foreach (var member in members)
            {
                var expression = member.Ser.EmitRead(code, "reader");
                code.Line("result." + Discovery.Escape(member.Name) + " = " + expression + ";");
            }

            code.Line("return result;");
            code.Close();
            code.Line();
            EmitRegistration(code, symbol, known, name);
        }

        private static void EmitRegistration(CodeWriter code, INamedTypeSymbol symbol, KnownSymbols known, string name)
        {
            var id = StableId.Compute(Discovery.FullName(symbol));
            code.Line(Never);
            code.Open("internal static class __NetPulseRegistration");
            code.Line("#if UNITY_EDITOR");
            code.Line("[global::UnityEditor.InitializeOnLoadMethod]");
            code.Line("#endif");
            code.Line("[global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]");
            code.Open("internal static void Register()");
            code.Line("global::NetPulse.Common.NetTypeRegistry.RegisterExtended<" + name + ">(" + id + ", static (w, v) => " + name + ".NetWrite(w, v), static r => " + name + ".NetRead(r));");

            if (known.ImplementsNetMessage(symbol))
            {
                code.Line("global::NetPulse.NetMessageRegistry.Register<" + name + ">(" + id + ", static (w, v) => " + name + ".NetWrite(w, v), static r => " + name + ".NetRead(r));");
            }

            code.Close();
            code.Close();
        }

        private sealed class Receiver : ISyntaxReceiver
        {
            public List<TypeDeclarationSyntax> Candidates { get; } = new List<TypeDeclarationSyntax>();

            public void OnVisitSyntaxNode(SyntaxNode node)
            {
                if ((node is ClassDeclarationSyntax || node is StructDeclarationSyntax) && ((TypeDeclarationSyntax)node).Modifiers.Any(SyntaxKind.PartialKeyword))
                {
                    Candidates.Add((TypeDeclarationSyntax)node);
                }
            }
        }
    }
}
